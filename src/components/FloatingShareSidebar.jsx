export default function FloatingShareSidebar({ title }) {
  const [visible, setVisible] = useState(false);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const onScroll = () => setVisible(window.scrollY > 300);
    window.addEventListener('scroll', onScroll, { passive: true });
    return () => window.removeEventListener('scroll', onScroll);
  }, []);

  const url = window.location.href;
  const tw = `https://twitter.com/intent/tweet?text=${encodeURIComponent(title)}&url=${encodeURIComponent(url)}`;
  const fb = `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`;
  const pin = `https://pinterest.com/pin/create/button/?url=${encodeURIComponent(url)}&description=${encodeURIComponent(title)}`;

  const handleIG = () => {
    const isMobile = /iPhone|iPad|iPod|Android/i.test(navigator.userAgent);
    if (isMobile && navigator.share) {
      navigator.share({ title, url }).catch(() => {});
    } else {
      navigator.clipboard.writeText(url);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    }
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(url);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const btnClass = "w-9 h-9 flex items-center justify-center border border-border text-muted-foreground hover:text-foreground hover:border-foreground transition-all duration-200 bg-background";

  return (
    <aside
      className="fixed left-4 top-1/2 -translate-y-1/2 z-40 hidden lg:flex flex-col gap-2 transition-all duration-500"
      style={{ opacity: visible ? 1 : 0, pointerEvents: visible ? 'auto' : 'none' }}
    >
      <p className="font-sans text-[9px] tracking-[0.2em] uppercase text-muted-foreground text-center mb-1">Share</p>
      <a href={tw} target="_blank" rel="noopener noreferrer" className={btnClass} title="Share on X"><XIcon /></a>
      <a href={fb} target="_blank" rel="noopener noreferrer" className={btnClass} title="Share on Facebook"><FBIcon /></a>
      <button onClick={handleIG} className={btnClass} title="Share to Instagram">{copied ? <span className="text-[9px]">✓</span> : <IGIcon />}</button>
      <a href={pin} target="_blank" rel="noopener noreferrer" className={btnClass} title="Share on Pinterest"><PinIcon /></a>
      <button onClick={handleCopy} className={btnClass} title="Copy link">{copied ? <span className="text-[9px]">✓</span> : <LinkIcon />}</button>
    </aside>
  );
}
